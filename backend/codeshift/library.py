def form(name, lang):
    return FORMS[name][LANGS.index(lang)] if name in FORMS else f"@{name}"


def round_away(x):
    r = math.floor(abs(x) + 0.5)
    return float(r if x >= 0 else -r)


def ipow(a, n):
    r = 1
    for _ in range(n):
        r *= a
    return r


